#!/usr/bin/env python3
"""
Extract a recorded piece's |a| buffer in the exact runtime format used
by DragonBoatModel.sampleBuffer: packed big-endian uint16 per sample,
one 16-bit sample = |a| in milli-g, sampled at 25 Hz.

Emits:
 - a raw .bin (for Python-side tests)
 - resources-selftest/: the bytes as hex strings in jsonData chunks, so
   the self-test loads and frees one chunk at a time (as constants in
   source the whole blob stays on the heap and the analyzer runs out of
   memory on a fenix 6)
 - source/AccelTestData.mc: sizes, expected count and the chunk ids
"""
import json
import math
import struct
import sys
from pathlib import Path

import fitdecode

import validate_mc_analyzer


def _field(frame, name):
    for f in frame.fields:
        if f.name == name:
            return f.value
    return None


def extract_mag_blob(fit_path: str, max_samples: int = 7500,
                     skip_samples: int = 0) -> bytes:
    out = bytearray()
    n_total = 0
    skipped = 0
    with fitdecode.FitReader(fit_path) as fit:
        for frame in fit:
            if not isinstance(frame, fitdecode.FitDataMessage):
                continue
            if frame.name != "record":
                continue
            ax = _field(frame, "accel_x")
            ay = _field(frame, "accel_y")
            az = _field(frame, "accel_z")
            an = _field(frame, "accel_n")
            if ax is None or ay is None or az is None:
                continue
            n = an if an is not None else len(ax)
            for i in range(n):
                if ax[i] is None or ay[i] is None or az[i] is None:
                    continue
                if skipped < skip_samples:
                    skipped += 1
                    continue
                if n_total >= max_samples:
                    break
                mag = int(round(math.sqrt(
                    ax[i] ** 2 + ay[i] ** 2 + az[i] ** 2)))
                if mag < 0:
                    mag = 0
                if mag > 65535:
                    mag = 65535
                out += struct.pack(">H", mag)
                n_total += 1
            if n_total >= max_samples:
                break
    return bytes(out)


RES_DIR = Path("resources-selftest")
PART_BYTES = 64        # bytes per hex string
PARTS_PER_CHUNK = 25   # hex strings per jsonData resource (1600 bytes)


def emit(blob: bytes, mc_path: str, num_samples: int,
         expected_strokes: int) -> int:
    """Write the blob as jsonData chunks plus the AccelTestData module.

    Hex strings, not array literals: the compiler's type checker recurses
    through array literals and blows its stack well before 7500 entries.
    Decoded at runtime with StringUtil.convertEncodedString.
    """
    parts = [blob[i:i + PART_BYTES].hex()
             for i in range(0, len(blob), PART_BYTES)]
    chunks = [parts[i:i + PARTS_PER_CHUNK]
              for i in range(0, len(parts), PARTS_PER_CHUNK)]

    RES_DIR.mkdir(exist_ok=True)
    for old in RES_DIR.glob("accel_test_*.json"):
        old.unlink()
    xml = ["<resources>"]
    for idx, chunk in enumerate(chunks):
        (RES_DIR / f"accel_test_{idx}.json").write_text(json.dumps(chunk))
        xml.append(f'    <jsonData id="accel_test_{idx}" '
                   f'filename="accel_test_{idx}.json"/>')
    xml.append("</resources>")
    (RES_DIR / "accel_test.xml").write_text("\n".join(xml) + "\n")

    lines = [
        "// GENERATED by extract_accel_blob.py — do not edit by hand.",
        "// |a| in milli-g, big-endian uint16 per sample, 25 Hz, stored as",
        "// hex strings in the jsonData chunks under resources-selftest/.",
        "// Only compiled into the self-test build (selftest.jungle).",
        "(:selftest)",
        "module AccelTestData {",
        f"    const NUM_SAMPLES = {num_samples};",
        "    // What validate_mc_analyzer.py (the Python mirror) counts.",
        f"    const EXPECTED_STROKES = {expected_strokes};",
        f"    const NUM_BYTES = {len(blob)};",
        "    const CHUNKS = [",
    ]
    for idx in range(len(chunks)):
        trailing = "," if idx < len(chunks) - 1 else ""
        lines.append(f"        Rez.JsonData.accel_test_{idx}{trailing}")
    lines.append("    ];")
    lines.append("}")
    Path(mc_path).write_text("\n".join(lines) + "\n")
    return len(chunks)


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else \
        "data/2026-04-16-05-59-47.fit"
    # Optional --max <samples>, --skip <samples>
    max_samples = 7500
    skip_samples = 0
    args = list(sys.argv[2:])
    while args:
        a = args.pop(0)
        if a == "--max":
            max_samples = int(args.pop(0))
        elif a == "--skip":
            skip_samples = int(args.pop(0))
    bin_dst = "data/accel_test.bin"
    mc_dst = "source/AccelTestData.mc"
    blob = extract_mag_blob(src, max_samples=max_samples,
                            skip_samples=skip_samples)
    Path(bin_dst).parent.mkdir(parents=True, exist_ok=True)
    Path(bin_dst).write_bytes(blob)
    mags = [v for (v,) in struct.iter_unpack(">H", blob)]
    expected = validate_mc_analyzer.analyze(mags)["strokes"]
    n_chunks = emit(blob, mc_dst, len(blob) // 2, expected)
    print(f"{src}: {len(blob)} bytes = {len(blob)//2} samples "
          f"({(len(blob)//2) / 25:.1f}s @ 25 Hz), "
          f"mirror expects {expected} strokes")
    print(f"  -> {bin_dst}")
    print(f"  -> {mc_dst}")
    print(f"  -> {RES_DIR}/ ({n_chunks} chunks)")
