#!/usr/bin/env python3
"""
Pack a recorded FIT file into JSON resources for live replay in the
Connect IQ simulator (whose own FIT playback never reaches the
accelerometer listener in SDK 8.3).

The data is split into CHUNK_SECONDS-long jsonData resources under
resources-replay/ so the app only holds one chunk in memory at a time;
source-replay/ReplayData.mc lists the chunk resource ids.

One hex string per 1 s FIT record, big-endian:
    n       uint8    number of |a| samples that follow (normally 25)
    hr      uint8    heart rate, 0 = none
    speed   uint16   cm/s, 0xFFFF = none
    lat     int32    semicircles, 0x7FFFFFFF = none
    lon     int32    semicircles
    mag[n]  uint16   |a| in milli-g

Usage: python3 make_replay_data.py data/<file>.fit [--skip SECONDS] [--max SECONDS]
"""
import json
import math
import shutil
import struct
import sys
from pathlib import Path

import fitdecode

ROOT = Path(__file__).parent
OUT = ROOT / "source-replay" / "ReplayData.mc"
RES_DIR = ROOT / "resources-replay"
CHUNK_SECONDS = 15
NO_SPEED = 0xFFFF
NO_POS = 0x7FFFFFFF


def _field(frame, name):
    for f in frame.fields:
        if f.name == name:
            return f.value
    return None


def pack_records(fit_path, skip=0, max_seconds=None):
    seconds = []
    with fitdecode.FitReader(fit_path) as fit:
        for frame in fit:
            if not isinstance(frame, fitdecode.FitDataMessage):
                continue
            if frame.name != "record":
                continue
            ax = _field(frame, "accel_x")
            ay = _field(frame, "accel_y")
            az = _field(frame, "accel_z")
            if ax is None or ay is None or az is None:
                continue
            an = _field(frame, "accel_n")
            n = an if an is not None else len(ax)
            mags = []
            for i in range(n):
                if ax[i] is None or ay[i] is None or az[i] is None:
                    continue
                m = int(round(math.sqrt(ax[i] ** 2 + ay[i] ** 2 + az[i] ** 2)))
                mags.append(max(0, min(65535, m)))

            hr = _field(frame, "heart_rate") or 0
            speed = _field(frame, "enhanced_speed")
            if speed is None:
                speed = _field(frame, "speed")
            speed = NO_SPEED if speed is None else min(int(round(speed * 100)), NO_SPEED - 1)
            lat = _field(frame, "position_lat")
            lon = _field(frame, "position_long")
            if lat is None or lon is None:
                lat = lon = NO_POS

            rec = struct.pack(">BBHii", len(mags), min(int(hr), 255), speed, lat, lon)
            rec += b"".join(struct.pack(">H", m) for m in mags)
            seconds.append(rec)
    seconds = seconds[skip:]
    if max_seconds is not None:
        seconds = seconds[:max_seconds]
    return seconds


def emit(seconds, src):
    chunks = [seconds[i:i + CHUNK_SECONDS]
              for i in range(0, len(seconds), CHUNK_SECONDS)]

    if RES_DIR.exists():
        shutil.rmtree(RES_DIR)
    RES_DIR.mkdir()
    xml = ["<resources>"]
    for idx, chunk in enumerate(chunks):
        (RES_DIR / f"replay_{idx}.json").write_text(
            json.dumps([rec.hex() for rec in chunk]))
        xml.append(f'    <jsonData id="replay_{idx}" filename="replay_{idx}.json"/>')
    xml.append("</resources>")
    (RES_DIR / "replay.xml").write_text("\n".join(xml) + "\n")

    lines = [
        "// GENERATED by make_replay_data.py — do not edit by hand.",
        f"// Source: {src}",
        "// Only compiled into the simulator replay build (sim.jungle).",
        "module ReplayData {",
        f"    const NUM_SECONDS = {len(seconds)};",
        f"    const CHUNK_SECONDS = {CHUNK_SECONDS};",
        "    const CHUNKS = [",
    ]
    for idx in range(len(chunks)):
        trailing = "," if idx < len(chunks) - 1 else ""
        lines.append(f"        Rez.JsonData.replay_{idx}{trailing}")
    lines += ["    ];", "}"]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args:
        sys.exit(__doc__)
    src = args.pop(0)
    skip, max_seconds = 0, None
    while args:
        a = args.pop(0)
        if a == "--skip":
            skip = int(args.pop(0))
        elif a == "--max":
            max_seconds = int(args.pop(0))
    seconds = pack_records(src, skip, max_seconds)
    emit(seconds, src)
    total = sum(r[0] for r in seconds)
    print(f"{src}: {len(seconds)} s, {total} accel samples -> {OUT}, {RES_DIR}/")
